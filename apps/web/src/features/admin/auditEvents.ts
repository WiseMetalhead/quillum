export function auditEventName(t: TFunction, event: string) {
  return t(`admin.auditEventNames.${event}`, {
    defaultValue: t('admin.unknownAuditEvent', { code: event }),
  })
}

export function matchingAuditEventCodes(t: TFunction, query: string) {
  const normalizedQuery = query.trim().toLocaleLowerCase()
  if (!normalizedQuery) return []

  return AUDIT_EVENT_CODES.filter((event) => (
    auditEventName(t, event).toLocaleLowerCase().includes(normalizedQuery)
  ))
}
